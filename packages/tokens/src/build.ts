function main() {
  console.log("Building @mizu-ui/tokens...");

  const raw = JSON.parse(readFileSync(TOKENS_PATH, "utf-8"));
  const { $schema, description, ...tokenCategories } = raw;

  const flat = flattenTokens(tokenCategories);

  mkdirSync(OUT_DIR, { recursive: true });
  mkdirSync(SRC_OUT, { recursive: true });

  // TypeScript
  const tsSource = generateTsSource(flat);
  writeFileSync(resolve(SRC_OUT, "index.ts"), tsSource);
  writeFileSync(resolve(OUT_DIR, "index.ts"), tsSource);

  // Light + Dark CSS
  const lightCss = generateLightCss(flat);
  writeFileSync(resolve(OUT_DIR, "light.css"), lightCss);

  const darkCss = generateDarkCss(flat);
  writeFileSync(resolve(OUT_DIR, "dark.css"), darkCss);

  // Tailwind v4 @theme
  const tailwindCss = generateTailwindCss(flat);
  writeFileSync(resolve(OUT_DIR, "tailwind.css"), tailwindCss);

  // Starlight
  const starlightCss = generateStarlightCss(flat);
  writeFileSync(resolve(OUT_DIR, "starlight.css"), starlightCss);

  console.log(`Generated ${flat.size} tokens`);
  console.log("Output: dist/{index.ts, light.css, dark.css, tailwind.css, starlight.css}");
}

main();
