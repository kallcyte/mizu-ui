import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "../../..");
const TOKENS_PATH = resolve(ROOT, "tokens.json");
const OUT_DIR = resolve(__dirname, "../dist");
const SRC_OUT = resolve(__dirname, "../src");

interface Token {
  $value: string | number | string[];
  $type: string;
  $description?: string;
}

interface TokenGroup {
  [key: string]: Token | TokenGroup;
}

function isToken(obj: unknown): obj is Token {
  return obj !== null && typeof obj === "object" && "$value" in (obj as Record<string, unknown>);
}

function flattenTokens(obj: TokenGroup | Token, prefix: string[] = []): Map<string, Token> {
  const result = new Map<string, Token>();

  for (const [key, value] of Object.entries(obj)) {
    const path = [...prefix, key];

    if (isToken(value)) {
      result.set(path.join("/"), value);
    } else if (typeof value === "object" && value !== null) {
      const nested = flattenTokens(value as TokenGroup, path);
      for (const [k, v] of nested) {
        result.set(k, v);
      }
    }
  }

  return result;
}

function toCamelCase(segments: string[]): string {
  return segments.map((s, i) => (i === 0 ? s : s.charAt(0).toUpperCase() + s.slice(1))).join("");
}

function toConstName(segments: string[]): string {
  return segments.map((s) => s.replace(/-/g, "_").toUpperCase()).join("_");
}

function toConstNameFromPath(path: string): string {
  return toConstName(path.split("/"));
}

function generateType(value: unknown): string {
  if (typeof value === "number") return "number";
  if (Array.isArray(value)) return "string[]";
  return "string";
}

function generateValue(value: unknown, type: string): string {
  if (type === "number") return String(value);
  return JSON.stringify(value);
}

/**
 * Convert a token path (slash-separated) into a flat list of hyphenated segments.
 */
function pathToSegments(path: string): string[] {
  return path.split("/");
}

/**
 * Map a token path to a @theme variable name (Tailwind v4 convention).
 */
function toThemeVarName(path: string): string {
  const segments = pathToSegments(path);
  const root = segments[0];
  const rest = segments
    .slice(1)
    .map((s) => camelToKebab(s))
    .join("-");

  switch (root) {
    case "color":
      return `--color-${rest}`;
    case "fontFamily":
      return `--font-family-${rest}`;
    case "fontSize":
      return `--text-${rest}`;
    case "fontWeight":
      return `--font-weight-${rest}`;
    case "lineHeight":
      return `--leading-${rest}`;
    case "letterSpacing":
      return `--tracking-${rest}`;
    case "shadow":
      return `--shadow-${rest}`;
    case "sizing":
      return `--sizing-${rest}`;
    case "zIndex":
      return `--z-${rest}`;
    case "duration":
      return `--duration-${rest}`;
    case "ease":
      return `--ease-${rest}`;
    default:
      return `--${segments.join("-")}`;
  }
}

/**
 * Format a token value for use as a CSS custom property value.
 * Font-family arrays become comma-separated quoted strings.
 */
function formatCssValue(value: unknown, type: string): string {
  if (type === "fontFamily" && Array.isArray(value)) {
    return value.map((name) => (/[\s"]/.test(name) ? `"${name}"` : name)).join(", ");
  }
  return String(value);
}

/**
 * Map a token path to a raw CSS variable name (kebab-case segments).
 * For dark tokens, the "dark" segment is dropped so the var overrides its light counterpart.
 */
function toCssVarName(path: string): string {
  const segments = pathToSegments(path);
  if (segments[1] === "dark" && (segments[0] === "color" || segments[0] === "shadow")) {
    return `--${segments[0]}-${segments.slice(2).join("-")}`;
  }
  return `--${segments.map((s) => camelToKebab(s)).join("-")}`;
}

function camelToKebab(s: string): string {
  return s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function generateTsSource(flat: Map<string, Token>): string {
  const lines: string[] = [];
  lines.push("// Auto-generated by build.ts — do not edit manually");
  lines.push(`// Source: tokens.json`);
  lines.push("");
  lines.push("export interface Token {");
  lines.push("  value: string | number | readonly string[];");
  lines.push("  type: string;");
  lines.push("  description?: string;");
  lines.push("}");
  lines.push("");

  for (const [path, token] of flat) {
    const segments = pathToSegments(path);
    const constName = toConstName(segments);
    const value = generateValue(token.$value, token.$type);
    const isFontFamily = token.$type === "fontFamily";

    lines.push(`/** ${token.$description ?? path} */`);
    if (isFontFamily) {
      lines.push(`export const ${constName}: string[] = ${value};`);
    } else {
      lines.push(`export const ${constName} = ${value} as const;`);
    }
  }

  lines.push("");

  lines.push("/** Flat map of all tokens keyed by slash-separated path */");
  lines.push("export const tokens: Record<string, Token> = {");
  for (const [path, token] of flat) {
    const constName = toConstNameFromPath(path);
    lines.push(`  "${path}": { value: ${constName}, type: "${token.$type}" },`);
  }
  lines.push("};");
  lines.push("");

  lines.push(
    "/** Token values mapped to CSS custom property names (light mode only — dark mode overrides live in dark.css) */"
  );
  lines.push("export const cssVariables: Record<string, string | number | readonly string[]> = {");
  for (const [path, token] of flat) {
    if (isDarkPath(path)) continue;
    const cssVar = toCssVarName(path);
    const constName = toConstNameFromPath(path);
    lines.push(`  "${cssVar}": ${constName},`);
  }
  lines.push("}");
  lines.push("");

  return lines.join("\n");
}

function generateLightCss(flat: Map<string, Token>): string {
  const lines: string[] = [];
  lines.push("/* Auto-generated by build.ts — do not edit manually */");
  lines.push("/* Source: tokens.json — light-mode CSS custom properties */");
  lines.push("");
  lines.push(":root {");
  for (const [path, token] of flat) {
    if (isDarkPath(path)) continue;
    const cssVar = toCssVarName(path);
    const value = formatCssValue(token.$value, token.$type);
    lines.push(`  ${cssVar}: ${value};`);
  }
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function generateDarkCss(flat: Map<string, Token>): string {
  const lines: string[] = [];
  lines.push("/* Auto-generated by build.ts — do not edit manually */");
  lines.push("/* Source: tokens.json — dark-mode CSS custom property overrides */");
  lines.push("");
  lines.push('[data-theme="dark"] {');
  for (const [path, token] of flat) {
    if (!isDarkPath(path)) continue;
    const cssVar = toCssVarName(path);
    const value = formatCssValue(token.$value, token.$type);
    lines.push(`  ${cssVar}: ${value};`);
  }
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function generateTailwindCss(flat: Map<string, Token>): string {
  const lines: string[] = [];
  lines.push("/* Auto-generated by build.ts — do not edit manually */");
  lines.push("/* Source: tokens.json — Tailwind v4 @theme tokens + dark overrides */");
  lines.push("");
  // @import "tailwindcss" is handled by @tailwindcss/vite plugin
  // lines.push('@import "tailwindcss";');
  lines.push("");
  lines.push("@theme {");

  // Font-family shortcuts so Tailwind generates `font-sans` / `font-mono` / `font-serif`.
  const fontFamilies: Array<{ key: string; segments: string[]; cssValue: string }> = [];
  for (const [path, token] of flat) {
    if (isDarkPath(path)) continue;
    const segments = pathToSegments(path);
    const themeVar = toThemeVarName(path);
    const value = formatCssValue(token.$value, token.$type);
    lines.push(`  ${themeVar}: ${value};`);
    if (segments[0] === "fontFamily") {
      const aliasName = segments[1];
      fontFamilies.push({
        key: aliasName,
        segments,
        cssValue: `var(--font-family-${aliasName})`,
      });
    }
  }

  for (const ff of fontFamilies) {
    lines.push(`  --font-${ff.key}: ${ff.cssValue};`);
  }

  lines.push("}");
  lines.push("");

  lines.push('[data-theme="dark"] {');
  for (const [path, token] of flat) {
    if (!isDarkPath(path)) continue;
    const segments = pathToSegments(path);
    const themeVar = `--${segments[0]}-${segments.slice(2).join("-")}`;
    const value = formatCssValue(token.$value, token.$type);
    lines.push(`  ${themeVar}: ${value};`);
  }
  lines.push("}");
  lines.push("");

  return lines.join("\n");
}

/**
 * A path is "dark" if its second segment is "dark" (e.g. color/dark/... or shadow/dark/...).
 * The dark segment is dropped when emitting CSS variables so the dark value overrides
 * the light value at the same var name.
 */
function isDarkPath(path: string): boolean {
  const segments = pathToSegments(path);
  return segments[1] === "dark" && (segments[0] === "color" || segments[0] === "shadow");
}

